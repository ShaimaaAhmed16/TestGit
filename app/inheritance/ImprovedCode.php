class Details{
    public string $name;
    public string $brand;
    public string $model;

    public function __construct(string $name,string $brand,string $model)
    {
        $this->name = $name;
        $this->brand = $brand;
        $this->model = $model;
    }

    public function getDetails():string
    {
        return "Name : {$this->name},Brand : {$this->brand} ,Model : {$this->model} ";
    }

}

class CarCode extends Details{
    private int $numDoors;
    public function __construct($name, $brand, $model,$numDoors)
    {
        parent::__construct($name, $brand, $model);
        $this->numDoors = $numDoors;
    }

    public function getDetails(): string
    {
        return parent::getDetails()."Doors : {$this->numDoors}"; // TODO: Change the autogenerated stub
    }
}

