<?php
class Car {
    public string $brand;
    public string $model;
    public int $numDoors;

    public function __construct(string $brand, string $model, int $numDoors) {
        $this->brand = $brand;
        $this->model = $model;
        $this->numDoors = $numDoors;
    }

    public function getDetails(): string {
        return "Car: {$this->brand} {$this->model}, Doors: {$this->numDoors}";
    }
}

class Motorcycle {
    public string $brand;
    public string $model;
    public bool $hasSidecar;

    public function __construct(string $brand, string $model, bool $hasSidecar) {
        $this->brand = $brand;
        $this->model = $model;
        $this->hasSidecar = $hasSidecar;
    }

    public function getDetails(): string {
        return "Motorcycle: {$this->brand} {$this->model}, Sidecar: " . ($this->hasSidecar ? "Yes" : "No");
    }
}

